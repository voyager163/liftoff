import { type Component, placedIn } from "../../domain/project/config.ts";
import { renderAgentIntegration } from "../../generators/skills.ts";
import type {
  Artifact,
  ComponentPlugin,
  GenerationContext,
  ProjectPlugin,
} from "../contracts/project-plugin.ts";

/** The part each kind of component is, for those with a directory of their own. */
const PART: Partial<Record<ComponentPlugin["kind"], Component>> = {
  stack: "backend",
  frontend: "frontend",
  infrastructure: "infrastructure",
};

/**
 * What lives where: the starter's layout in a new project, or, in an adopted
 * one, whose application is its own, each part's directory.
 */
function layoutLines({ components, layout, application }: GenerationContext): string[] {
  if (application) {
    return components
      .flatMap((component) => component.layout)
      .map((entry) => `- \`${placedIn(layout, entry.path)}\` ${entry.purpose}.`);
  }
  return components.flatMap(({ kind, summary }) => {
    const part = PART[kind];
    if (part === undefined) return [];
    const directory = layout[part];
    return directory === "."
      ? [`- \`.\` the ${part}, at the repository root (${summary}).`]
      : [`- \`${directory}/\` the ${part} (${summary}).`];
  });
}

function agentsMarkdown(context: GenerationContext): string {
  const { config, components, workflow, layout: directories } = context;
  const checks = components
    .flatMap((component) => component.checks)
    .map(
      (check) =>
        `| \`${placedIn(directories, check.directory)}\` | \`${check.command}\` | ${check.name} |`,
    );
  const layout = layoutLines(context);
  return [
    `# ${config.name}`,
    "",
    `${components.map((component) => component.summary).join("; ")}. Generated by Liftoff; edit this file as the project grows.`,
    "",
    "## Checks",
    "",
    "Run each command from the directory shown, and show its output before saying a change works.",
    "",
    "| Directory | Command | What it checks |",
    "| --- | --- | --- |",
    ...checks,
    "",
    "## Layout",
    "",
    ...layout,
    "",
    ...(workflow.guide.length === 0
      ? []
      : ["## Specifications", "", ...workflow.guide.flatMap((paragraph) => [paragraph, ""])]),
    "## Conventions",
    "",
    "- Pull requests target `develop`. Name branches `feature/…`, `fix/…`, `chore/…`, `docs/…` or `ci/…`.",
    "- `.github/review-policy.yml` sets how much review a change needs; `liftoff review classify` shows it.",
    "- Never commit secrets. Configuration examples hold placeholders only.",
    "- Never weaken a check to get green: no skipped tests, lowered thresholds or ignored failures.",
    "",
    "## Review",
    "",
    "Before opening a pull request, use the `liftoff-verify`, `liftoff-code-review` and `liftoff-pr` skills. See [REVIEW.md](REVIEW.md) for what reviewers look for.",
    "",
  ].join("\n");
}

const CLAUDE_MD = [
  "@AGENTS.md",
  "",
  "## Claude Code",
  "",
  "Use the project skills in `.claude/skills/`, for example `/liftoff-verify`, `/liftoff-code-review` and `/liftoff-pr`.",
  "",
].join("\n");

/**
 * Coding-agent integration: AGENTS.md for every host, CLAUDE.md for Claude
 * Code, and the review skills and verifier agent in each host's native place.
 * Manual projects with no agents get none of it.
 */
export const agentsPlugin: ProjectPlugin = {
  id: "agents/integration",
  kind: "agents",
  version: "1",
  summary: "Instructions, skills and agents for the selected coding-agent hosts",
  templateRoots: [],
  artifacts(context) {
    if (context.hosts.length === 0) return [];
    const files: Artifact[] = [
      { path: "AGENTS.md", ownership: "seeded", content: agentsMarkdown(context) },
    ];
    if (context.hosts.includes("claude"))
      files.push({ path: "CLAUDE.md", ownership: "seeded", content: CLAUDE_MD });
    for (const file of renderAgentIntegration({
      hosts: context.hosts,
      skills: context.skills,
      agents: context.agents,
    })) {
      files.push({ ...file, ownership: "managed" });
    }
    return files;
  },
};
