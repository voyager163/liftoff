// Bundles the review-policy check into one dependency-free script that CI
// runs with the runner's own Node. With --check, fails if the committed copy
// differs from a fresh build, so the bundle can never drift from src/.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { build } from "esbuild";

const root = path.resolve(import.meta.dirname, "..");
const target = ".github/liftoff/review-policy.mjs";

export async function bundleReviewPolicy(): Promise<string> {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ["src/ci/review-policy-entry.ts"],
    bundle: true,
    write: false,
    platform: "node",
    format: "esm",
    target: "node20",
    minify: true,
    legalComments: "eof",
    charset: "utf8",
    banner: {
      js: [
        "// Generated by Liftoff from src/ci/review-policy-entry.ts. Do not edit.",
        "// Liftoff is GPL-3.0-only: https://github.com/voyager163/liftoff",
        "// Bundles zod (MIT), yaml (ISC) and picomatch (MIT).",
        // CommonJS dependencies require Node built-ins, which ESM lacks.
        'import { createRequire as __liftoffRequire } from "node:module";',
        "const require = __liftoffRequire(import.meta.url);",
      ].join("\n"),
    },
    logLevel: "silent",
  });
  const [file] = result.outputFiles;
  if (!file) throw new Error("esbuild produced no output");
  return file.text;
}

if (import.meta.main) {
  const fresh = await bundleReviewPolicy();
  const destination = path.join(root, target);
  if (process.argv.includes("--check")) {
    let committed = "";
    try {
      committed = readFileSync(destination, "utf8");
    } catch {
      // Reported below as a mismatch.
    }
    if (committed !== fresh) {
      console.error(`${target} is out of date; run "npm run build:ci-bundle" and commit it`);
      process.exit(1);
    }
    console.log(`${target} is up to date`);
  } else {
    writeFileSync(destination, fresh);
    console.log(`wrote ${target} (${Math.round(fresh.length / 1024)} KiB)`);
  }
}
