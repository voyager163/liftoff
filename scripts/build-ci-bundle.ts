// Bundles each CI check into one dependency-free script that CI runs with the
// runner's own Node. With --check, fails if a committed copy differs from a
// fresh build, so the bundles can never drift from src/.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { build } from "esbuild";

const root = path.resolve(import.meta.dirname, "..");
/** Each committed bundle and the entry point it is built from. */
export const BUNDLES: Readonly<Record<string, string>> = {
  ".github/liftoff/review-policy.mjs": "src/ci/review-policy-entry.ts",
  ".github/liftoff/governance-drift.mjs": "src/ci/governance-drift-entry.ts",
  ".github/liftoff/ai-review.mjs": "src/ci/ai-review-entry.ts",
  ".github/liftoff/review-metrics.mjs": "src/ci/review-metrics-entry.ts",
};

export async function bundle(entry: string): Promise<string> {
  const result = await build({
    absWorkingDir: root,
    entryPoints: [entry],
    bundle: true,
    write: false,
    metafile: true,
    platform: "node",
    format: "esm",
    target: "node20",
    minify: true,
    legalComments: "eof",
    charset: "utf8",
    logLevel: "silent",
  });
  const [file] = result.outputFiles;
  if (!file) throw new Error("esbuild produced no output");

  const packages = new Set<string>();
  for (const input of Object.keys(result.metafile.inputs)) {
    const match = /^node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input);
    if (match?.[1]) packages.add(match[1]);
  }
  const licensed = [...packages].sort().map((name) => {
    const manifest = JSON.parse(
      readFileSync(path.join(root, "node_modules", name, "package.json"), "utf8"),
    );
    return `${name} (${manifest.license ?? "unknown license"})`;
  });
  const header = [
    `// Generated by Liftoff from ${entry}. Do not edit.`,
    "// Liftoff is GPL-3.0-only: https://github.com/voyager163/liftoff",
    ...(licensed.length > 0 ? [`// Bundles ${licensed.join(", ")}.`] : []),
    // CommonJS dependencies require Node built-ins, which ESM lacks.
    'import { createRequire as __liftoffRequire } from "node:module";',
    "const require = __liftoffRequire(import.meta.url);",
  ];
  return `${header.join("\n")}\n${file.text}`;
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [target, entry] of Object.entries(BUNDLES)) {
    const fresh = await bundle(entry);
    const destination = path.join(root, target);
    if (check) {
      let committed = "";
      try {
        committed = readFileSync(destination, "utf8");
      } catch {
        // Reported below as out of date.
      }
      if (committed !== fresh) {
        console.error(`${target} is out of date; run "npm run build:ci-bundle" and commit it`);
        stale++;
      } else {
        console.log(`${target} is up to date`);
      }
    } else {
      writeFileSync(destination, fresh);
      console.log(`wrote ${target} (${Math.round(fresh.length / 1024)} KiB)`);
    }
  }
  if (stale > 0) process.exit(1);
}
